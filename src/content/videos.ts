/** The HLS ladder. Mux builds four rungs from 270x480 up to 1080x1920. */
export const streamUrl = (playbackId: string): string =>
  `https://stream.mux.com/${playbackId}.m3u8`;

/**
 * The poster frame, generated by Mux and free on every plan — so no still has to be cut by
 * hand, stored in `public/`, or kept in step when a clip is replaced. Width is the rendered
 * frame at 2x.
 */
export const posterUrl = (clip: Clip, width: number): string => {
  const at = clip.posterTime === undefined ? "" : `&time=${clip.posterTime}`;
  return `https://image.mux.com/${clip.playbackId}/thumbnail.webp?width=${width}&fit_mode=preserve${at}`;
};
