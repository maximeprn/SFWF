/* The festival's own footage, hosted on Mux.
 *
 * Only the playback ID lives here. It is a public identifier, not a secret — the API token
 * that put these on the account is in `.env.local` and is needed to upload, never to play.
 * The masters are in `video-source/`, which is gitignored: Mux is a delivery layer, not an
 * archive. Re-run `npm run mux:upload` after adding a clip and paste the new ID in.
 *
 * Every clip is 9:16 — shot vertical, delivered vertical, framed vertical. Nothing here is
 * cropped to fit a landscape box.
 */

export interface Clip {
  readonly id: string;
  /** Mux playback ID. Streams at https://stream.mux.com/{playbackId}.m3u8 */
  readonly playbackId: string;
  /** Spoken caption, and the accessible name of the button that starts it. */
  readonly caption: string;
  /** Whole seconds, for the mono meta line. Mux's own duration, rounded. */
  readonly seconds: number;
  /**
   * Which second Mux cuts the poster from. Left off, Mux picks the frame itself, and its
   * choice is not always the one that sells the clip — a talking head mid-sentence, or a
   * fade. Chosen against a contact sheet of the master, per clip.
   */
  readonly posterTime?: number;
}

